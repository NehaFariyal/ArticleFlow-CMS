const request = require('supertest');
const jwt = require('jsonwebtoken');
const https = require('https');
const { EventEmitter } = require('events');
const app = require('../server');
const {
  extractiveSummary,
  extractTags,
  generateSuggestion,
  summarizeArticle,
} = require('../services/aiWritingService');

const mockGeminiResponses = (responses) => jest.spyOn(https, 'request').mockImplementation((options, callback) => {
  const outgoingRequest = new EventEmitter();
  outgoingRequest.end = () => {
    const responseData = responses.shift();
    const response = new EventEmitter();
    response.statusCode = responseData.statusCode;
    response.setEncoding = jest.fn();
    callback(response);
    process.nextTick(() => {
      response.emit('data', JSON.stringify(responseData.body));
      response.emit('end');
    });
  };
  outgoingRequest.destroy = (error) => outgoingRequest.emit('error', error);
  return outgoingRequest;
});

describe('AI writing assistance', () => {
  const originalApiKey = process.env.GEMINI_API_KEY;
  const originalGeminiModel = process.env.GEMINI_MODEL;
  const originalJwtSecret = process.env.JWT_SECRET;
  const testJwtSecret = 'ai-writing-test-secret';

  beforeEach(() => {
    delete process.env.GEMINI_API_KEY;
    process.env.JWT_SECRET = testJwtSecret;
  });

  afterAll(() => {
    if (originalApiKey === undefined) {
      delete process.env.GEMINI_API_KEY;
    } else {
      process.env.GEMINI_API_KEY = originalApiKey;
    }
    if (originalGeminiModel === undefined) {
      delete process.env.GEMINI_MODEL;
    } else {
      process.env.GEMINI_MODEL = originalGeminiModel;
    }
    if (originalJwtSecret === undefined) {
      delete process.env.JWT_SECRET;
    } else {
      process.env.JWT_SECRET = originalJwtSecret;
    }
  });

  it('returns clearly identified rule-based title suggestions without an API key', async () => {
    const result = await generateSuggestion('titles', {
      title: 'Urban Gardens',
      content: 'Urban gardens make fresh food available in cities.',
    });

    expect(result.provider).toBe('rule-based');
    expect(result.message).toMatch(/not an AI model/);
    expect(result.value).toHaveLength(3);
    expect(result.value[0]).toContain('Urban Gardens');
  });

  it('extracts an article summary and relevant tags without an API key', async () => {
    const content = [
      'Community gardens bring neighbors together.',
      'Urban gardens also improve access to fresh food.',
      'Shared growing spaces support local biodiversity.',
      'These projects need long-term community support.',
    ].join(' ');

    const summary = await summarizeArticle(content);
    const tags = await generateSuggestion('tags', { content });

    expect(summary.provider).toBe('rule-based');
    expect(summary.value).toBe(extractiveSummary(content, 5));
    expect(summary.message).toMatch(/not generated by an AI model/);
    expect(tags.provider).toBe('rule-based');
    expect(tags.value).toContain('gardens');
    expect(extractTags(content).length).toBeGreaterThan(0);
  });

  it('uses Gemini for writing assistance and long-form summaries when configured', async () => {
    const apiKey = 'test-only-gemini-key';
    const content = 'Community gardens bring neighbors together. Urban gardens improve access to fresh food.';
    const responseBodies = [
      { suggestions: ['A new title', 'Another title', 'A third title'] },
      { suggestion: 'A Gemini-generated article summary.' },
    ];
    const requestSpy = jest.spyOn(https, 'request').mockImplementation((options, callback) => {
      const outgoingRequest = new EventEmitter();
      outgoingRequest.end = () => {
        const response = new EventEmitter();
        response.statusCode = 200;
        response.setEncoding = jest.fn();
        callback(response);
        process.nextTick(() => {
          response.emit('data', JSON.stringify({
            candidates: [{
              content: {
                parts: [{ text: JSON.stringify(responseBodies.shift()) }],
              },
            }],
          }));
          response.emit('end');
        });
      };
      outgoingRequest.destroy = (error) => outgoingRequest.emit('error', error);
      return outgoingRequest;
    });
    process.env.GEMINI_API_KEY = apiKey;
    process.env.GEMINI_MODEL = 'gemini-3.5-flash-lite';

    try {
      const token = jwt.sign({ id: '66c9f1a00000000000000002' }, testJwtSecret);
      const writingResponse = await request(app)
        .post('/api/ai-writing/assist')
        .set('Authorization', `Bearer ${token}`)
        .send({ action: 'titles', title: 'Community Gardens', content });
      const summaryResponse = await request(app)
        .post('/api/ai-writing/summarize')
        .set('Authorization', `Bearer ${token}`)
        .send({ content });

      expect(writingResponse.statusCode).toBe(200);
      expect(writingResponse.body).toMatchObject({
        success: true,
        provider: 'gemini',
        value: ['A new title', 'Another title', 'A third title'],
      });
      expect(summaryResponse.statusCode).toBe(200);
      expect(summaryResponse.body).toMatchObject({
        success: true,
        provider: 'gemini',
        value: 'A Gemini-generated article summary.',
      });
      expect(requestSpy).toHaveBeenCalledTimes(2);
      for (const [options] of requestSpy.mock.calls) {
        expect(options.hostname).toBe('generativelanguage.googleapis.com');
        expect(options.path).toContain('gemini-3.5-flash-lite:generateContent');
        expect(options.path).toContain(encodeURIComponent(apiKey));
      }
      expect(JSON.stringify([writingResponse.body, summaryResponse.body])).not.toContain(apiKey);
    } finally {
      requestSpy.mockRestore();
      delete process.env.GEMINI_API_KEY;
    }
  });

  it('retries a temporary Gemini 429 and succeeds on the next attempt', async () => {
    const requestSpy = mockGeminiResponses([
      {
        statusCode: 429,
        body: { error: { status: 'RESOURCE_EXHAUSTED', message: 'High demand; try again later.' } },
      },
      {
        statusCode: 200,
        body: {
          candidates: [{
            content: { parts: [{ text: JSON.stringify({ suggestions: ['Retry title'] }) }] },
          }],
        },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'The service is overloaded.' } },
      },
      {
        statusCode: 200,
        body: {
          candidates: [{
            content: { parts: [{ text: JSON.stringify({ suggestion: 'Retry summary.' }) }] },
          }],
        },
      },
    ]);
    process.env.GEMINI_API_KEY = 'test-only-gemini-key';

    try {
      const result = await generateSuggestion('titles', {
        title: 'Community Gardens',
        content: 'Community gardens help neighbors grow fresh food.',
      });
      const summary = await summarizeArticle(
        'Community gardens bring neighbors together. Urban gardens improve access to fresh food.'
      );

      expect(result).toMatchObject({
        provider: 'gemini',
        value: ['Retry title'],
      });
      expect(summary).toMatchObject({
        provider: 'gemini',
        value: 'Retry summary.',
      });
      expect(requestSpy).toHaveBeenCalledTimes(4);
    } finally {
      requestSpy.mockRestore();
      delete process.env.GEMINI_API_KEY;
    }
  });

  it('retries Gemini at most twice then returns a clearly labeled fallback', async () => {
    const requestSpy = mockGeminiResponses([
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
      {
        statusCode: 503,
        body: { error: { status: 'UNAVAILABLE', message: 'High demand. Service is temporarily unavailable.' } },
      },
    ]);
    process.env.GEMINI_API_KEY = 'test-only-gemini-key';

    try {
      const result = await generateSuggestion('titles', {
        title: 'Community Gardens',
        content: 'Community gardens help neighbors grow fresh food.',
      });
      const summary = await summarizeArticle(
        'Community gardens bring neighbors together. Urban gardens improve access to fresh food.'
      );

      expect(result.provider).toBe('rule-based');
      expect(result.message).toMatch(/not AI-generated/);
      expect(summary.provider).toBe('rule-based');
      expect(summary.message).toMatch(/not AI-generated/);
      expect(requestSpy).toHaveBeenCalledTimes(6);
    } finally {
      requestSpy.mockRestore();
      delete process.env.GEMINI_API_KEY;
    }
  });

  it('does not retry permanent Gemini credential or permission errors', async () => {
    const requestSpy = mockGeminiResponses([
      {
        statusCode: 403,
        body: { error: { status: 'PERMISSION_DENIED', message: 'API key does not have permission.' } },
      },
    ]);
    process.env.GEMINI_API_KEY = 'test-only-gemini-key';

    try {
      const result = await generateSuggestion('titles', {
        title: 'Community Gardens',
        content: 'Community gardens help neighbors grow fresh food.',
      });

      expect(result.provider).toBe('rule-based');
      expect(result.message).toMatch(/not AI-generated/);
      expect(requestSpy).toHaveBeenCalledTimes(1);
    } finally {
      requestSpy.mockRestore();
      delete process.env.GEMINI_API_KEY;
    }
  });

  it('retains rule-based results and labels them when Gemini is unavailable', async () => {
    const requestSpy = jest.spyOn(https, 'request').mockImplementation(() => {
      const outgoingRequest = new EventEmitter();
      outgoingRequest.end = () => process.nextTick(() => outgoingRequest.emit('error', new Error('network unavailable')));
      outgoingRequest.destroy = (error) => outgoingRequest.emit('error', error);
      return outgoingRequest;
    });
    process.env.GEMINI_API_KEY = 'test-only-gemini-key';

    try {
      const writingResult = await generateSuggestion('titles', {
        title: 'Community Gardens',
        content: 'Community gardens help neighbors grow fresh food.',
      });
      const summaryResult = await summarizeArticle(
        'Community gardens bring neighbors together. Urban gardens improve access to fresh food.'
      );

      expect(writingResult.provider).toBe('rule-based');
      expect(writingResult.message).toMatch(/not AI-generated/);
      expect(summaryResult.provider).toBe('rule-based');
      expect(summaryResult.message).toMatch(/not AI-generated/);
      expect(requestSpy).toHaveBeenCalledTimes(2);
    } finally {
      requestSpy.mockRestore();
      delete process.env.GEMINI_API_KEY;
    }
  });

  it('rejects unauthenticated access to AI writing endpoints', async () => {
    const response = await request(app)
      .post('/api/ai-writing/assist')
      .send({ action: 'titles', content: 'Some draft content' });

    expect(response.statusCode).toBe(401);
    expect(response.body.success).toBe(false);
  });

  it('serves authenticated suggestions and long-form summaries without Gemini', async () => {
    const token = jwt.sign({ id: '66c9f1a00000000000000002' }, testJwtSecret);
    const content = [
      'Community gardens bring neighbors together.',
      'Urban gardens improve access to fresh food and support local biodiversity.',
      'These shared growing spaces also help communities build lasting connections.',
      'Successful projects need long-term planning and community support.',
    ].join(' ');

    const suggestionResponse = await request(app)
      .post('/api/ai-writing/assist')
      .set('Authorization', `Bearer ${token}`)
      .send({ action: 'takeaways', content });
    const summaryResponse = await request(app)
      .post('/api/ai-writing/summarize')
      .set('Authorization', `Bearer ${token}`)
      .send({ content });

    expect(suggestionResponse.statusCode).toBe(200);
    expect(suggestionResponse.body).toMatchObject({
      success: true,
      action: 'takeaways',
      provider: 'rule-based',
    });
    expect(Array.isArray(suggestionResponse.body.value)).toBe(true);
    expect(summaryResponse.statusCode).toBe(200);
    expect(summaryResponse.body).toMatchObject({
      success: true,
      provider: 'rule-based',
    });
    expect(summaryResponse.body.value).toBeTruthy();
    expect(summaryResponse.body.message).toMatch(/not generated by an AI model/);
  });

  it('returns a clear validation error for empty article content', async () => {
    const token = jwt.sign({ id: '66c9f1a00000000000000002' }, testJwtSecret);
    const response = await request(app)
      .post('/api/ai-writing/summarize')
      .set('Authorization', `Bearer ${token}`)
      .send({ content: '   ' });

    expect(response.statusCode).toBe(400);
    expect(response.body.message).toBe('Article content is required.');
  });
});
